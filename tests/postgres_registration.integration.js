const assert = require("node:assert/strict");
const test = require("node:test");
const pool = require("../db");

const upsertSql = `
    INSERT INTO pg_temp.chats_registration_test
        (student_id, student_name, phone, consultant_mode, username,
         first_name, last_name, phone_verified, last_activity_at)
    VALUES ($1,$2,$3,false,$4,$5,$6,true,now())
    ON CONFLICT (student_id) DO UPDATE SET
        student_name=EXCLUDED.student_name,
        phone=EXCLUDED.phone,
        username=EXCLUDED.username,
        first_name=EXCLUDED.first_name,
        last_name=EXCLUDED.last_name,
        phone_verified=true,
        last_activity_at=now()
    RETURNING id, student_id AS telegram_id, phone, phone_verified,
              created_at AS registered_at
`;

test("real PostgreSQL supports new and repeated Telegram registration", async () => {
    const client = await pool.connect();
    try {
        await client.query("BEGIN");
        await client.query(`
            CREATE TEMP TABLE chats_registration_test (
                id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                student_id bigint NOT NULL UNIQUE,
                student_name varchar(255),
                phone varchar(50),
                created_at timestamp DEFAULT CURRENT_TIMESTAMP,
                consultant_mode boolean DEFAULT false,
                username text,
                first_name text,
                last_name text,
                phone_verified boolean NOT NULL DEFAULT false,
                last_activity_at timestamptz
            ) ON COMMIT DROP
        `);
        const first = await client.query(upsertSql, [
            "7421578363", "Test User", "+77010000001", "test", "Test", "User",
        ]);
        assert.equal(first.rows[0].telegram_id, "7421578363");
        assert.equal(first.rows[0].phone_verified, true);

        const repeated = await client.query(upsertSql, [
            "7421578363", "Updated User", "+77010000002", "updated", "Updated", "User",
        ]);
        assert.equal(repeated.rows[0].phone, "+77010000002");
        const count = await client.query(
            "SELECT count(*)::int AS count FROM pg_temp.chats_registration_test"
        );
        assert.equal(count.rows[0].count, 1);
        await client.query("ROLLBACK");
    } finally {
        client.release();
        await pool.end();
    }
});

test("a sequence behind primary-key data reproduces chats_pkey failure", async () => {
    const {Pool} = require("pg");
    const isolatedPool = new Pool({
        host: process.env.DB_HOST,
        port: Number(process.env.DB_PORT),
        database: process.env.DB_NAME,
        user: process.env.DB_USER,
        password: process.env.DB_PASSWORD,
        max: 1,
    });
    const client = await isolatedPool.connect();
    try {
        await client.query("BEGIN");
        await client.query("CREATE TEMP SEQUENCE chats_bad_seq START 1");
        await client.query(`
            CREATE TEMP TABLE chats_bad_sequence (
                id integer PRIMARY KEY DEFAULT nextval('pg_temp.chats_bad_seq'),
                student_id bigint NOT NULL UNIQUE
            ) ON COMMIT DROP
        `);
        await client.query(
            "INSERT INTO pg_temp.chats_bad_sequence(id,student_id) VALUES(1,100)"
        );
        await client.query("SAVEPOINT before_bad_insert");
        let failure;
        try {
            await client.query(
                "INSERT INTO pg_temp.chats_bad_sequence(student_id) VALUES(200) ON CONFLICT(student_id) DO UPDATE SET student_id=EXCLUDED.student_id"
            );
        } catch (error) {
            failure = error;
            await client.query("ROLLBACK TO SAVEPOINT before_bad_insert");
        }
        assert.equal(failure.code, "23505");
        assert.equal(failure.constraint, "chats_bad_sequence_pkey");

        await client.query(`
            SELECT setval(
                'pg_temp.chats_bad_seq'::regclass,
                (SELECT max(id) + 1 FROM pg_temp.chats_bad_sequence),
                false
            )
        `);
        const repaired = await client.query(
            "INSERT INTO pg_temp.chats_bad_sequence(student_id) VALUES(200) RETURNING id"
        );
        assert.equal(repaired.rows[0].id, 2);
        await client.query("ROLLBACK");
    } finally {
        client.release();
        await isolatedPool.end();
    }
});
